import { spawn } from "node:child_process";
import { existsSync, readFileSync, writeFileSync, unlinkSync } from "node:fs";
import { createServer } from "node:net";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dashboardEnvFile = resolve(root, "apps/dashboard/.env.local");
const extensionEnvFile = resolve(root, "apps/extension/.env.local");
const productionExtensionEnvFile = resolve(root, "apps/extension/.env.production");
const generatedEnvFile = resolve(root, "apps/extension/.env.development.local");
const manifestFile = resolve(root, "apps/extension/dist/manifest.json");
const marker = "# Generated by npm run dev:tracking";
const localOrigin = "http://localhost:3001";
const children = [];
let stopping = false;

function variable(file, name) {
  if (!existsSync(file)) throw new Error(`Missing ${file}. Copy its .env.example and fill in your Supabase values.`);
  const line = readFileSync(file, "utf8").split(/\r?\n/).find((item) => item.startsWith(`${name}=`));
  const value = line?.slice(name.length + 1).trim().replace(/^['"]|['"]$/g, "");
  if (!value || value.includes("your-project") || value.startsWith("your-")) throw new Error(`${name} is missing from ${file}`);
  return value;
}

function start(command, args, env = process.env) {
  const child = spawn(command, args, { cwd: root, env, stdio: "inherit", detached: true });
  children.push(child);
  child.on("error", (error) => stop(`Could not start ${command}: ${error.message}`));
  child.on("exit", (code) => { if (!stopping) stop(`${command} stopped unexpectedly (${code ?? "signal"})`); });
  return child;
}

function stop(reason) {
  if (stopping) return;
  stopping = true;
  if (reason) console.error(`\n${reason}`);
  for (const child of children) {
    if (child.pid) {
      try { process.kill(-child.pid, "SIGTERM"); } catch { /* Already stopped. */ }
    }
  }
  if (existsSync(generatedEnvFile) && readFileSync(generatedEnvFile, "utf8").startsWith(marker)) unlinkSync(generatedEnvFile);
  process.exitCode = reason ? 1 : 0;
}

async function assertPortAvailable() {
  await new Promise((accept, reject) => {
    const server = createServer();
    server.once("error", () => reject(new Error("Port 3001 is already in use. Stop that server before starting dev:tracking.")));
    server.listen(3001, "127.0.0.1", () => server.close(accept));
  });
}

async function waitForHealth(origin) {
  const deadline = Date.now() + 60_000;
  while (!stopping && Date.now() < deadline) {
    try {
      const response = await fetch(`${origin}/api/health`, { signal: AbortSignal.timeout(2500), cache: "no-store" });
      if (response.ok && (await response.json()).ok === true) return;
    } catch { /* The server is still starting. */ }
    await new Promise((done) => setTimeout(done, 500));
  }
  throw new Error(`Health check never passed at ${origin}/api/health`);
}

async function waitForExtension(pixelOrigin) {
  const deadline = Date.now() + 30_000;
  while (!stopping && Date.now() < deadline) {
    try {
      const manifest = JSON.parse(readFileSync(manifestFile, "utf8"));
      if (manifest.name === "OpenTrackMail (Development)" &&
          manifest.host_permissions?.includes(`${localOrigin}/*`) &&
          manifest.host_permissions?.includes(`${pixelOrigin}/*`)) return;
    } catch { /* The first extension build is still running. */ }
    await new Promise((done) => setTimeout(done, 300));
  }
  throw new Error("The development extension did not build with both required host permissions.");
}

async function main() {
  const dashboardSupabase = variable(dashboardEnvFile, "NEXT_PUBLIC_SUPABASE_URL");
  const extensionSupabase = variable(extensionEnvFile, "VITE_SUPABASE_URL");
  const productionSupabase = variable(productionExtensionEnvFile, "VITE_SUPABASE_URL");
  const pixelOrigin = new URL(variable(productionExtensionEnvFile, "VITE_PIXEL_ORIGIN")).origin;
  if (dashboardSupabase !== extensionSupabase || dashboardSupabase !== productionSupabase) {
    throw new Error("Local dashboard, development extension, and production pixel must use the same Supabase project.");
  }
  variable(dashboardEnvFile, "SUPABASE_SERVICE_ROLE_KEY");
  variable(dashboardEnvFile, "EVENT_HASH_SECRET");
  if (existsSync(generatedEnvFile) && !readFileSync(generatedEnvFile, "utf8").startsWith(marker)) {
    throw new Error(`Move your custom ${generatedEnvFile} before running dev:tracking.`);
  }
  await assertPortAvailable();
  await waitForHealth(pixelOrigin);

  const dashboardEnv = {
    ...process.env,
    NEXT_PUBLIC_SITE_URL: localOrigin,
    NEXT_PUBLIC_APP_URL: localOrigin,
    TRACKING_PIXEL_ORIGIN: pixelOrigin,
    ALLOWED_EXTENSION_ORIGINS: "",
  };
  start("npm", ["run", "dev", "-w", "@opentrackmail/dashboard"], dashboardEnv);
  await waitForHealth(localOrigin);

  writeFileSync(generatedEnvFile, `${marker}\nVITE_API_URL=${localOrigin}\nVITE_PIXEL_ORIGIN=${pixelOrigin}\nVITE_APP_URL=${localOrigin}/app\nVITE_SUPABASE_URL=${extensionSupabase}\n`);
  start("npm", ["run", "dev", "-w", "@opentrackmail/extension"]);
  await waitForExtension(pixelOrigin);
  console.log(`\nDevelopment tracking is ready.\nDashboard/API: ${localOrigin}/app\nRecipient pixel: ${pixelOrigin}\nExtension: ${resolve(root, "apps/extension/dist")}\nReload the unpacked extension and refresh Gmail. Keep this command running while sending.\n`);
}

process.on("SIGINT", () => stop());
process.on("SIGTERM", () => stop());

main().catch((error) => stop(error instanceof Error ? error.message : String(error)));
